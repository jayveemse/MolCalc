"""
Check how well a candidate temperature profile T(z) explains an experimental
pressure reading, given a known mole count and a trusted volume profile.

Workflow this supports:
  1. You know n_mol at some timestep (e.g. from the start-of-run fill).
  2. You have a volume profile V(z) you trust (exported from MolCalc's
     geometry-based volume profiler).
  3. You have a candidate T(z) at that same timestep -- here, sparse points
     from a SolidWorks thermal simulation.
  4. This script fits a cubic spline through the T(z) points, resamples it
     onto the volume profile's z-grid, integrates
         P = n / sum(Vi / (Zi * R * Ti))
     using the same real-gas solver as MolCalc's Pressure Trace Synthesizer
     (molcalc.pressure_trace_synthesizer._synth_compute_P), and reports
     P_calc -- optionally against a measured P_exp.

Usage:
    python check_t_profile.py --n-mol 0.0452 \
        --volume-csv volume_profile.csv \
        --temp-csv sw_temps_120min.csv \
        --p-exp 2.35 --gas Nitrogen

CSV formats:
    volume_csv : columns "Axial Position" (mm), "Total Volume" (mm^3) -- MolCalc's own
                 volumeDF column names/units, per-slice (NOT cumulative). Export your
                 real one straight from a run with:
                     volumeDF[['Axial Position', 'Total Volume']].to_csv(path, index=False)
    temp_csv   : columns "z_mm", "T_C"  (sparse SW points; need >= 4 for a
                 well-posed cubic spline)
"""
import argparse
import os
import sys

import numpy as np
import pandas as pd
from scipy.interpolate import CubicSpline

# Reuse the already-validated real-gas pressure solver from the main app
# instead of re-deriving the physics here.
_MOLCALC_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if _MOLCALC_ROOT not in sys.path:
    sys.path.insert(0, _MOLCALC_ROOT)
from molcalc.pressure_trace_synthesizer import _synth_compute_P

R = 8.3145  # J/(mol*K)

# Same Z-factor lookup convention as the rest of MolCalc: one .npz per gas,
# with T_K / P_MPa / Z arrays, generated by generate_Z_table.py.
_Z_TABLE_DIR = os.path.join(
    os.path.expanduser('~'),
    'Lehigh University Dropbox/ENG-MATSGroup/MATS - Collaboration/Data/'
    'Parsers/MolCalc/File Dependencies',
)
_GAS_FILE_MAP = {'Nitrogen': 'N2_Z.npz'}


def load_z_interpolator(gas):
    """Return (z_interp, T_min, T_max, P_min, P_max). z_interp is None -> ideal gas (Z=1)."""
    from scipy.interpolate import RegularGridInterpolator
    stem = _GAS_FILE_MAP.get(gas)
    if stem is None:
        print(f"No Z-table mapping for gas '{gas}' -- using ideal gas (Z=1).")
        return None, 250.0, 2000.0, 0.1, 50.0
    path = os.path.join(_Z_TABLE_DIR, stem)
    try:
        data = np.load(path)
        interp = RegularGridInterpolator(
            (data['T_K'], data['P_MPa']), data['Z'],
            bounds_error=False, fill_value=None)
        print(f"Z-table loaded for {gas} ({path}).")
        return (interp, float(data['T_K'].min()), float(data['T_K'].max()),
                float(data['P_MPa'].min()), float(data['P_MPa'].max()))
    except Exception as e:
        print(f"Z-table not found/loadable ({e}) -- using ideal gas (Z=1).")
        return None, 250.0, 2000.0, 0.1, 50.0


def fit_temperature_profile(temp_csv):
    """Fit a cubic spline through sparse (z_mm, T_C) points, e.g. from a SolidWorks sim."""
    df = pd.read_csv(temp_csv)
    if not {'z_mm', 'T_C'}.issubset(df.columns):
        raise ValueError(f"{temp_csv} must have columns 'z_mm' and 'T_C', got {list(df.columns)}")
    df = df.sort_values('z_mm').drop_duplicates(subset='z_mm')
    if len(df) < 4:
        print(f"Warning: only {len(df)} T point(s) -- cubic spline is poorly constrained.")
    z_known = df['z_mm'].to_numpy(dtype=float)
    T_known_C = df['T_C'].to_numpy(dtype=float)
    spline = CubicSpline(z_known, T_known_C, extrapolate=False)
    return spline, z_known, T_known_C


def evaluate_profile(spline, z_known, T_known_C, z_query):
    """
    Evaluate the spline at z_query, clamping to the nearest known temperature
    outside the fitted z-range instead of letting a cubic extrapolate through
    data that doesn't support it. Warns if a non-trivial chunk of the volume
    profile falls outside the SW sim's z-coverage, since that volume's
    contribution to P is then only a flat assumption, not a fit.
    """
    T_C = spline(z_query)
    below = z_query < z_known.min()
    above = z_query > z_known.max()
    if below.any() or above.any():
        n_clamped = int(below.sum() + above.sum())
        print(f"Warning: {n_clamped}/{len(z_query)} volume-profile z points fall outside "
              f"the T-profile's z range [{z_known.min():.0f}, {z_known.max():.0f}] mm -- "
              f"clamped to the nearest known temperature there.")
    T_C[below] = T_known_C[0]
    T_C[above] = T_known_C[-1]
    return T_C


def main():
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--n-mol', type=float, required=True,
                     help='Known mole count at this timestep (mol).')
    ap.add_argument('--volume-csv', required=True,
                     help="CSV with MolCalc's native volumeDF columns: "
                          "'Axial Position' (mm), 'Total Volume' (mm^3, per-slice).")
    ap.add_argument('--temp-csv', required=True,
                     help='CSV with sparse columns z_mm, T_C (e.g. from a SolidWorks sim).')
    ap.add_argument('--p-exp', type=float, default=None,
                     help='Measured pressure at this timestep (MPa), for comparison.')
    ap.add_argument('--gas', default='Nitrogen', help='Gas species (default: Nitrogen).')
    ap.add_argument('--no-plot', action='store_true', help='Skip the spline sanity-check plot.')
    args = ap.parse_args()

    vol_df = pd.read_csv(args.volume_csv)
    if not {'Axial Position', 'Total Volume'}.issubset(vol_df.columns):
        raise ValueError(f"{args.volume_csv} must have columns 'Axial Position' and "
                          f"'Total Volume' (MolCalc's native volumeDF columns), "
                          f"got {list(vol_df.columns)}")
    z_v = vol_df['Axial Position'].to_numpy(dtype=float)
    V_mm3 = vol_df['Total Volume'].to_numpy(dtype=float)
    V_m3 = V_mm3 / 1e9

    spline, z_known, T_known_C = fit_temperature_profile(args.temp_csv)
    T_C_on_v_grid = evaluate_profile(spline, z_known, T_known_C, z_v)
    T_K_on_v_grid = T_C_on_v_grid + 273.15

    z_interp, T_min, T_max, P_min, P_max = load_z_interpolator(args.gas)

    P_Pa = _synth_compute_P(args.n_mol, T_K_on_v_grid, V_m3, z_interp=z_interp,
                             z_T_min=T_min, z_T_max=T_max, z_P_min=P_min, z_P_max=P_max, R=R)
    P_MPa = P_Pa / 1e6

    print(f"\nn_mol            = {args.n_mol:.6e} mol")
    print(f"V_total          = {V_m3.sum() * 1e6:.3f} mL")
    print(f"T-profile input  = {len(z_known)} point(s), "
          f"z = [{z_known.min():.0f}, {z_known.max():.0f}] mm, "
          f"T = [{T_known_C.min():.1f}, {T_known_C.max():.1f}] degC")
    print(f"T range on V-grid= [{T_C_on_v_grid.min():.1f}, {T_C_on_v_grid.max():.1f}] degC")
    print(f"P_calc           = {P_MPa:.4f} MPa")
    if args.p_exp is not None:
        err = P_MPa - args.p_exp
        pct = 100 * err / args.p_exp if args.p_exp else float('nan')
        print(f"P_exp            = {args.p_exp:.4f} MPa")
        print(f"Difference       = {err:+.4f} MPa  ({pct:+.2f}%)")

    if not args.no_plot:
        import matplotlib.pyplot as plt
        fig, (ax_t, ax_v) = plt.subplots(2, 1, figsize=(8, 6), sharex=True)
        z_dense = np.linspace(z_known.min(), z_known.max(), 400)
        ax_t.plot(z_dense, spline(z_dense), '-', label='Cubic spline fit')
        ax_t.plot(z_known, T_known_C, 'o', color='black', label='SW points')
        ax_t.set_ylabel('T (degC)')
        ax_t.legend()
        title = f'T profile fit  |  P_calc = {P_MPa:.4f} MPa'
        if args.p_exp is not None:
            title += f'  |  P_exp = {args.p_exp:.4f} MPa'
        ax_t.set_title(title)
        ax_v.plot(z_v, V_mm3, '-', color='gray')
        ax_v.set_ylabel('V per slice (mm3)')
        ax_v.set_xlabel('z (mm)')
        plt.tight_layout()
        plt.show()


if __name__ == '__main__':
    main()
